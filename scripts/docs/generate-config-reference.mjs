#!/usr/bin/env node
/**
 * Renders the configuration reference from the tables the code already reads.
 *
 * The alternative is a page someone keeps true by hand, and this repository
 * has measured what that costs: reviewing the hand-written reference in #1114
 * against the source found it naming `S3_ENDPOINT_URL` as required when it is
 * optional, omitting `S3_SESSION_TOKEN` entirely, and describing an encryption
 * failure mode backwards. Five of its seven review findings were the page
 * restating something the schemas already encoded, and disagreeing.
 *
 * So the facts come from `provider-seams.ts` and `config-groups.ts` — the same
 * tables that generate the boot-time check and type the written config — and
 * the page is a build artifact. `tests/architecture/config-reference-is-generated.test.ts`
 * fails when the committed file no longer matches what this prints.
 *
 * What it deliberately does not cover: the variables no table describes.
 * Prose about *why* you would choose a provider belongs in a written page;
 * this one answers "what does choosing it require".
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const { PROVIDER_SEAMS, FIELD_GROUPS } = require('@ragenai/env');

const SOURCE = 'scripts/docs/generate-config-reference.mjs';

/** A table row per variable, so requiredness is never a sentence to misread. */
function variableTable(entries, fields) {
  const rows = entries.map(({ name, required }) => {
    const field = fields?.[name];
    return `| \`${name}\` | ${field ? `\`${field}\`` : '—'} | ${required ? '**required**' : 'optional'} |`;
  });

  return ['| Variable | Config field | |', '|---|---|---|', ...rows].join('\n');
}

function entriesOf(spec) {
  return [
    ...spec.required.map((name) => ({ name, required: true })),
    ...(spec.optional ?? []).map((name) => ({ name, required: false })),
  ];
}

function renderSeam(seam) {
  const out = [
    `### ${seam.label}`,
    '',
    `Chosen with \`${seam.discriminant}\`${
      seam.defaultVariant
        ? `, which defaults to \`${seam.defaultVariant}\`.`
        : '. Unset selects nothing and requires nothing.'
    }`,
    '',
  ];

  for (const [variant, spec] of Object.entries(seam.variants)) {
    const entries = entriesOf(spec);

    out.push(`#### \`${seam.discriminant}=${variant}\``, '', spec.summary, '');
    out.push(
      entries.length
        ? variableTable(entries, spec.fields)
        : 'Needs nothing else.',
      '',
    );
  }

  return out.join('\n');
}

function renderGroup(group) {
  const out = [`### ${group.label}`, '', group.summary, ''];
  const entries = entriesOf(group);

  out.push(
    entries.length ? variableTable(entries, group.fields) : 'Nothing to set.',
    '',
  );

  for (const { vars, label } of group.pairs ?? []) {
    out.push(
      `${label} is all-or-nothing: \`${vars[0]}\` and \`${vars[1]}\` must both be set or both omitted.`,
      '',
    );
  }

  return out.join('\n');
}

export function renderConfigReference() {
  return [
    '---',
    'sidebar_position: 9',
    '---',
    '',
    `<!-- Generated by ${SOURCE}. Do not edit by hand: a test fails when this file and the tables disagree. -->`,
    '',
    '# Configuration reference',
    '',
    'Every variable here is described once, in `packages/env`, and read from',
    'there by three things: the check each app runs at boot, the type of the',
    '`ragen.config.ts` the installer writes, and this page. They cannot drift',
    'from each other, which is the point — an earlier hand-written version of',
    'this reference disagreed with the code about which S3 variables were',
    'required.',
    '',
    'A **required** variable is required *once you have chosen that provider*,',
    'not in general. Everything optional has a working default in code.',
    '',
    '## Providers',
    '',
    'One variable picks an implementation, and that choice decides what else',
    'you have to set.',
    '',
    ...PROVIDER_SEAMS.map(renderSeam),
    '## Settings',
    '',
    'No choice to make — these are the same variables whatever else is',
    'configured.',
    '',
    ...FIELD_GROUPS.map(renderGroup),
  ].join('\n');
}

const target = join(
  import.meta.dirname,
  '..',
  '..',
  'apps',
  'docs',
  'docs',
  'configuration-reference.md',
);

if (process.argv[1] === import.meta.filename) {
  writeFileSync(target, renderConfigReference());
  console.log(`wrote ${target}`);
}
